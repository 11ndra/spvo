#!/usr/bin/env bash
set -euo pipefail

echo "=== Сетевые интерфейсы ==="
ip -br link

echo
echo "=== IPv4-адреса ==="
ip -br -4 addr

echo
echo "=== Маршрут по умолчанию ==="
ip route show default || true

echo
cat <<'MSG'
Обычно интерфейс с маршрутом default относится к NAT.
Учебный интерфейс IDPS-LAB — второй виртуальный адаптер. На нём должен быть
статический адрес 10.13.37.10/24 (клиент) или 10.13.37.20/24 (сервер) и НЕ
должно быть отдельного шлюза по умолчанию.
MSG
